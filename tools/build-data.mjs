// Rebuilds data/advisor-data.js from the JSON files in data/.
//
//   node tools/build-data.mjs           # write data/advisor-data.js (and re-format the JSON)
//   node tools/build-data.mjs --check   # exit 1 if advisor-data.js is out of date
//
// The JSON files are the source of truth (easy to review, diff and import into
// another app). advisor-data.js is the same data wrapped as a plain script so the
// page works from GitHub Pages *and* when opened straight from disk (file://),
// where browsers block fetch() of local JSON.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = join(root, "data");
const read = (f) => JSON.parse(readFileSync(join(dataDir, f), "utf8"));

// One record per line: compact, but a changed model shows up as a one-line diff.
const formatList = (arr) => "[\n" + arr.map((x) => JSON.stringify(x)).join(",\n") + "\n]\n";
const formatObj = (o) => JSON.stringify(o, null, 2) + "\n";

const pumps = read("pumps.json");
const swg = read("swg.json");
const filters = read("filters.json");
const rules = read("rules.json");
const meta = { ...read("meta.json"), pumpCount: pumps.length, swgCount: swg.length, filterCount: filters.length };

const files = {
  "pumps.json": formatList(pumps),
  "swg.json": formatList(swg),
  "filters.json": formatList(filters),
  "rules.json": formatObj(rules),
  "meta.json": formatObj(meta),
};
const bundle = { swg, pumps, rules, meta, filters };
files["advisor-data.js"] =
  "/* GENERATED by tools/build-data.mjs from data/*.json - edit the JSON files, then rebuild. */\n" +
  "window.ADVISOR_DATA = " + JSON.stringify(bundle) + ";\n";

const check = process.argv.includes("--check");
let stale = [];
for (const [name, text] of Object.entries(files)) {
  const path = join(dataDir, name);
  let current = null;
  try { current = readFileSync(path, "utf8"); } catch {}
  if (current === text) continue;
  if (check) stale.push(name);
  else writeFileSync(path, text);
}
if (check && stale.length) {
  console.error("Out of date: " + stale.join(", ") + "\nRun: node tools/build-data.mjs");
  process.exit(1);
}
console.log(check ? "data files are up to date" : `built data/advisor-data.js (${pumps.length} pumps, ${swg.length} SWGs, ${filters.length} filters, ${Object.keys(rules).length} rules)`);
